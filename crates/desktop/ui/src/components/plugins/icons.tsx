/** A placement's icon: `svg:<data-url>` → an <img>; a known lucide name → that icon; anything else → `Puzzle`. */
export function PluginIcon({ icon, className }: { icon: string; className?: string }) {
  if (icon.startsWith('svg:')) {
    const src = icon.slice(4)
    // Only an inline SVG data URL; anything else (a remote URL) falls back to the generic glyph.
    if (src.startsWith('data:image/svg+xml')) return <img src={src} alt="" aria-hidden className={cn('size-4 shrink-0', className)} />
  }
  const Icon = Object.hasOwn(PLUGIN_ICONS, icon) ? (PLUGIN_ICONS[icon] as LucideIcon) : Puzzle
  return <Icon aria-hidden className={className} />
}
