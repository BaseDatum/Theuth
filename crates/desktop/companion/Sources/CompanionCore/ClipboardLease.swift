import Foundation

/// One pasteboard item as a bag of representations (`UTI → data`), the shape `NSPasteboardItem` round-trips.
public struct PasteboardItem: Equatable, Sendable {
    public var types: [String: Data]
    public init(_ types: [String: Data]) { self.types = types }
    public subscript(type: String) -> Data? { types[type] }
}

/// The clipboard the lease works on (153 §13.3). D2 implements it over `NSPasteboard.general`; tests use an in-memory one.
/// Reference semantics expected (a pasteboard is shared state), so no method is `mutating`.
public protocol Pasteboard: AnyObject {
    /// `NSPasteboard.changeCount`.
    var changeCount: Int { get }
    /// Every item with every representation; throws when a representation cannot be read (→ `clipboardSnapshotFailed`).
    func snapshot() throws -> [PasteboardItem]
    /// `clearContents()` + write; answers the new `changeCount` (→ `clipboardWriteFailed` on throw).
    func write(_ items: [PasteboardItem]) throws -> Int
    /// Put the snapshot back (`clearContents()` + write of every representation); empty = just clear (→ `restoreFailed`).
    func restore(_ items: [PasteboardItem]) throws
}

/// §13.3: snapshot → write (markers + session id) → paste → settle (restore only if still ours). Generation-stamped so a
/// late settle of an earlier gesture never touches a newer lease or the user's new clipboard. Pure: timing is the caller's
/// (`settleMs`), the paste keystroke is the caller's.
public struct ClipboardLease {
    /// The representation we write and the type that survives an oversized snapshot.
    public static let textType = "public.utf8-plain-text"
    /// Our item carries the gesture id under this type; its presence at settle time means "still ours".
    public static let sessionType = "io.theuth.dictation-session"
    /// nspasteboard.org conventions: clipboard managers skip the item; nothing of the dictation stays in a history.
    public static let markerTypes = ["org.nspasteboard.TransientType", "org.nspasteboard.ConcealedType", "org.nspasteboard.AutoGeneratedType"]
    /// Settle this long after the paste keystroke.
    public static let settleMs = 500
    /// A representation above this is dropped from the snapshot; the restore then keeps only the text types (§13.3 step 1).
    public static let maxRepresentationBytes = 32 * 1024 * 1024
    /// Representations kept when the snapshot is oversized.
    public static let textTypes: Set<String> = [textType, "public.utf16-external-plain-text", "public.rtf", "public.html", "NSStringPboardType"]

    public enum Phase: Equatable, Sendable { case idle, held, written, pasted, settled }

    /// §13.5 kinds, with the underlying pasteboard error.
    public enum Failure: Error { case clipboardSnapshotFailed(Error), clipboardWriteFailed(Error), restoreFailed(Error) }

    public enum SettleOutcome: Equatable, Sendable {
        /// Still ours → the snapshot is back.
        case restored
        /// The user copied meanwhile → their clipboard is left alone.
        case keptUsers
        /// `leaveTextOnClipboard` → the dictated text stays.
        case leftText
        /// `generation` is not the live one → nothing done.
        case stale
        /// Nothing was written in this generation (the write failed or never happened).
        case nothing
    }

    public let pasteboard: any Pasteboard
    /// Setting "Leave the dictated text on the clipboard" (`ModeKeySettings.leaveTextOnClipboard`, default off).
    public var leaveTextOnClipboard: Bool
    public private(set) var phase: Phase = .idle
    /// Bumped by every `begin`; `settle(generation:)` with an older one is a no-op.
    public private(set) var generation = 0
    /// The user's clipboard as of `begin`.
    public private(set) var snapshot: [PasteboardItem] = []
    /// `changeCount` returned by our write; the settle restores only while the pasteboard still reports it.
    public private(set) var writeChangeCount: Int?
    public private(set) var session: String?
    public private(set) var text: String?

    public init(pasteboard: any Pasteboard, leaveTextOnClipboard: Bool = false) {
        self.pasteboard = pasteboard; self.leaveTextOnClipboard = leaveTextOnClipboard
    }

    /// Step 1: snapshot every item (oversized representations → text types only). Answers the new generation.
    @discardableResult
    public mutating func begin() throws -> Int {
        generation += 1
        writeChangeCount = nil; session = nil; text = nil; snapshot = []
        phase = .idle
        let items: [PasteboardItem]
        do { items = try pasteboard.snapshot() } catch { throw Failure.clipboardSnapshotFailed(error) }
        snapshot = Self.capped(items)
        phase = .held
        return generation
    }

    /// Step 2: one item — the text + the three markers + the session id (the gesture id).
    public mutating func write(_ text: String, session: String) throws {
        let item = Self.item(text: text, session: session)
        do { writeChangeCount = try pasteboard.write([item]) } catch { throw Failure.clipboardWriteFailed(error) }
        self.session = session; self.text = text
        phase = .written
    }

    /// Step 3 happened (⌘V posted); the caller schedules `settle` after `settleMs`.
    public mutating func pasteIssued() { if phase == .written { phase = .pasted } }

    /// Step 5: restore the snapshot iff `generation` is live, the pasteboard still reports our write's `changeCount` and still
    /// carries our session id; otherwise leave whatever the user put there. A restore error is `Failure.restoreFailed`.
    public mutating func settle(generation g: Int) throws -> SettleOutcome {
        guard g == generation else { return .stale }
        guard phase == .written || phase == .pasted, let count = writeChangeCount, let session else { return .nothing }
        phase = .settled
        if leaveTextOnClipboard { return .leftText }
        guard pasteboard.changeCount == count, Self.isOurs(try? pasteboard.snapshot(), session: session, text: text) else { return .keptUsers }
        do { try pasteboard.restore(snapshot) } catch { throw Failure.restoreFailed(error) }
        return .restored
    }

    /// The item of step 2.
    public static func item(text: String, session: String) -> PasteboardItem {
        var types = [textType: Data(text.utf8), sessionType: Data(session.utf8)]
        for m in markerTypes { types[m] = Data() }
        return PasteboardItem(types)
    }

    /// "Still ours": some item carries our session id and (when readable) our text.
    public static func isOurs(_ items: [PasteboardItem]?, session: String, text: String?) -> Bool {
        guard let items else { return false }
        return items.contains { item in
            guard let s = item[sessionType], String(decoding: s, as: UTF8.self) == session else { return false }
            guard let text, let t = item[textType] else { return true }
            return String(decoding: t, as: UTF8.self) == text
        }
    }

    /// Step 1's cap: any representation over `maxRepresentationBytes` → only the text types of every item survive.
    public static func capped(_ items: [PasteboardItem]) -> [PasteboardItem] {
        let oversized = items.contains { $0.types.values.contains { $0.count > maxRepresentationBytes } }
        guard oversized else { return items }
        return items.compactMap { item in
            let kept = item.types.filter { textTypes.contains($0.key) && $0.value.count <= maxRepresentationBytes }
            return kept.isEmpty ? nil : PasteboardItem(kept)
        }
    }
}
