/// Registry name of the [`Apps`] actor.
pub const APP_ACTOR: &str = "app";

/// The library compatibility hash the desktop renderer, the helper and every
/// committed app agree on; generated by `packages/apps` (`bun run generate`).
/// One hex line with a trailing newline: use [`hash`] or `.trim()`.
pub const HASH: &str = include_str!("../../../packages/apps/generated/library-hash.txt");

/// [`HASH`] without the newline.
pub fn hash() -> &'static str {
    HASH.trim()
}

/// The bundled `apps` skill (46 §9): `apps.md` with the generated component
/// catalog and the library hash filled in. Written to
/// `<data_dir>/skills/apps.md` by the binary's first run.
pub fn skill() -> String {
    const SKILL: &str = include_str!("../apps.md");
    const CATALOG: &str = include_str!("../../../packages/apps/generated/catalog.txt");
    SKILL
        .replace("{{catalog}}", CATALOG.trim_end())
        .replace("{{hash}}", hash())
}

/// `app:` config section (46 §9). `enabled: false` registers nothing:
/// no tool, prompt, helper or actor; existing app artifacts stay readable
/// as source through the artifact plugin.
#[derive(Clone, Debug, Serialize, Deserialize)]
#[serde(default)]
pub struct AppConfig {
    /// Master switch.
    pub enabled: bool,
}

impl Default for AppConfig {
    fn default() -> Self {
        Self { enabled: true }
    }
}

/// Where the helper executable lives: `THEUTH_APP_PARSER` (developer/test
/// override; a file path, never a runtime to invoke) or the immutable
/// `theuth-app-parser-<hash>` beside the running binary (46 §2.1). The hash in
/// the name is not trusted: [`helper::Helper`] runs `--version` and refuses a
/// mismatch before the first request.
pub fn helper_path() -> PathBuf {
    if let Some(p) = std::env::var_os("THEUTH_APP_PARSER").filter(|p| !p.is_empty()) {
        return PathBuf::from(p);
    }
    let dir = std::env::current_exe()
        .ok()
        .and_then(|p| p.parent().map(std::path::Path::to_path_buf))
        .unwrap_or_default();
    dir.join(format!(
        "theuth-app-parser-{}{}",
        hash(),
        std::env::consts::EXE_SUFFIX
    ))
}

/// How a client reached a bound tool (46 §6.2).
#[derive(Clone, Copy, Debug, PartialEq, Eq, Serialize, Deserialize, schemars::JsonSchema)]
#[cfg_attr(feature = "ts", derive(ts_rs::TS), ts(export))]
#[serde(rename_all = "snake_case")]
pub enum Trigger {
    /// First evaluation of a Query when the view opened.
    Load,
    /// Timer refresh.
    Refresh,
    /// Query arguments changed because state changed.
    StateChange,
    /// A real pointer/keyboard activation of an action (`@Run`).
    Press,
}

impl Trigger {
    /// Only a press carries consent (46 §6.1).
    pub fn is_press(self) -> bool {
        matches!(self, Self::Press)
    }
}

/// Lifecycle of one app tool call as the client sees it.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Serialize, Deserialize, schemars::JsonSchema)]
#[cfg_attr(feature = "ts", derive(ts_rs::TS), ts(export))]
#[serde(rename_all = "snake_case")]
pub enum CallStatus {
    /// Dispatched, not finished (a duplicate request id met an in-flight press).
    Running,
    /// Finished with a non-error output.
    Succeeded,
    /// Finished with an error output, or refused by an argument/limit check.
    Failed,
    /// Durable record was `running` when the harness restarted, or no such request.
    Unknown,
    /// Policy is `Ask` and nothing activated it: render a Load/Refresh affordance.
    NeedsApproval,
    /// Never dispatched: tool missing/hidden, identity changed, bad args,
    /// policy `Deny`, or a mutation without activation.
    Unavailable,
    /// No slot under §7 for a press; try again.
    Busy,
    /// Superseded by a newer generation or argument value, or the view closed
    /// before the read finished.
    Cancelled,
}

impl CallStatus {
    /// Whether `is_error` is set for this status.
    pub fn is_error(self) -> bool {
        !matches!(self, Self::Running | Self::Succeeded | Self::NeedsApproval)
    }
}

/// One `Query`/`Mutation` statement pinned to the tool it was validated against.
#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize, schemars::JsonSchema)]
#[cfg_attr(feature = "ts", derive(ts_rs::TS), ts(export))]
pub struct AppBinding {
    /// Statement identifier in the source.
    pub statement_id: String,
    /// Registry tool name.
    pub tool: String,
    /// `"query"` or `"mutation"`.
    pub kind: String,
    /// Risk at publish time (display; the live policy decides).
    pub risk: tools::Risk,
    /// [`tools::ToolInspection::identity`] at publish time; the registry
    /// refuses any other identity at dispatch.
    pub identity: String,
}

/// A located validation problem.
#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize, schemars::JsonSchema)]
#[cfg_attr(feature = "ts", derive(ts_rs::TS), ts(export))]
pub struct AppDiagnostic {
    /// Statement id, or `""` for the whole program.
    pub at: String,
    /// Human message.
    pub message: String,
    /// Machine class (helper protocol `DiagnosticCode`, plus `tool-identity`
    /// for a binding whose live tool no longer matches).
    pub code: String,
}

/// A committed app as a client opens it (`get_app`, 46 §6.3).
#[derive(Clone, Debug, Serialize, Deserialize, schemars::JsonSchema, kameo::Reply)]
#[cfg_attr(feature = "ts", derive(ts_rs::TS), ts(export))]
pub struct AppDoc {
    /// The record.
    pub artifact: artifact::Artifact,
    /// Canonical validated source.
    pub source: String,
    /// Library hash the source was validated against; the client refuses to
    /// execute when it differs from its own.
    pub library_hash: String,
    /// Declared Query/Mutation bindings.
    pub bindings: Vec<AppBinding>,
    /// Publish-time diagnostics (empty for a committed app) plus, per bound
    /// tool, whether it is currently missing or rebound.
    pub diagnostics: Vec<AppDiagnostic>,
    /// Declared `$state` defaults.
    pub state: serde_json::Value,
    /// Durable pressed invocations of this record, newest first (≤64), so a
    /// reopened or reconnected view shows what its actions did.
    #[serde(default)]
    pub recent_calls: Vec<AppRecentCall>,
}

/// One durable pressed invocation as a reopened view sees it (46 §6.4).
#[derive(Clone, Debug, Serialize, Deserialize, schemars::JsonSchema)]
#[cfg_attr(feature = "ts", derive(ts_rs::TS), ts(export))]
pub struct AppRecentCall {
    /// The invocation.
    pub request_id: String,
    /// The bound statement.
    pub statement_id: String,
    /// Resolved tool.
    pub tool: String,
    /// Current status (`running`, `succeeded`, `failed`, `unknown`, …).
    pub status: CallStatus,
    /// Text content of the stored result, or the status explanation.
    pub content: String,
    /// Stored structured result, when kept.
    pub structured: Option<serde_json::Value>,
    /// Mirrors [`CallStatus::is_error`].
    pub is_error: bool,
}

/// Arguments of `app_call_tool`.
#[derive(Clone, Debug, Serialize, Deserialize, schemars::JsonSchema)]
#[cfg_attr(feature = "ts", derive(ts_rs::TS), ts(export))]
pub struct CallArgs {
    /// The app record.
    pub record_call_id: String,
    /// One open view; bound to the connection and record on first use.
    pub instance_id: String,
    /// Version of the view; a higher value adopts and discards older reads.
    #[cfg_attr(feature = "ts", ts(type = "number"))]
    pub generation: u64,
    /// The Query/Mutation statement.
    pub statement_id: String,
    /// Client-chosen, stable across retries of one invocation.
    pub request_id: String,
    /// Tool arguments as evaluated by the renderer.
    pub args: serde_json::Value,
    /// Why the call happens.
    pub trigger: Trigger,
    /// Required for [`Trigger::Press`], forbidden otherwise.
    pub action_id: Option<String>,
}

/// Result of `app_call_tool` / `app_call_status`.
#[derive(Clone, Debug, Serialize, Deserialize, schemars::JsonSchema, kameo::Reply)]
#[cfg_attr(feature = "ts", derive(ts_rs::TS), ts(export))]
pub struct AppToolResult {
    /// Echoed request id.
    pub request_id: String,
    /// Text content (tool text, or the refusal/error message).
    pub content: String,
    /// Machine-readable result, when the tool produced one.
    pub structured: Option<serde_json::Value>,
    /// Mirrors [`CallStatus::is_error`] for the MCP envelope conversion.
    pub is_error: bool,
    /// Lifecycle status.
    pub status: CallStatus,
}

impl AppToolResult {
    /// A result with no data for `status`.
    pub fn status(
        request_id: impl Into<String>,
        status: CallStatus,
        content: impl Into<String>,
    ) -> Self {
        Self {
            request_id: request_id.into(),
            content: content.into(),
            structured: None,
            is_error: status.is_error(),
            status,
        }
    }
}

/// Event: an app tool call changed status (46 §6.4). Wire shape
/// `{ "type": "AppCallChanged", … }`. Not a model turn.
#[derive(Clone, Debug, Serialize, Deserialize, schemars::JsonSchema)]
#[cfg_attr(feature = "ts", derive(ts_rs::TS), ts(export))]
#[serde(tag = "type")]
pub struct AppCallChanged {
    /// Owning session (from the record, never the client).
    pub session: SessionId,
    /// The app record.
    pub record_call_id: String,
    /// The invocation.
    pub request_id: String,
    /// The bound statement.
    pub statement_id: String,
    /// Resolved tool.
    pub tool: String,
    /// Risk bound at publish.
    pub risk: tools::Risk,
    /// Why it ran.
    pub trigger: Trigger,
    /// New status.
    pub status: CallStatus,
    /// Elapsed since admission, milliseconds.
    #[cfg_attr(feature = "ts", ts(type = "number"))]
    pub ms: u64,
}

impl wire::WireEvent for AppCallChanged {
    const TOPIC: &'static str = "app.calls";
}

/// Declare app wire contracts even when the app service is disabled.
pub async fn declare_wire(rt: &Runtime) -> anyhow::Result<()> {
    use wire::RuntimeWire as _;
    rt.register_wire_event::<AppCallChanged>().await?;
    Ok(())
}

/// The plugin (46 §2, §9): reads `app`, spawns [`Apps`] as [`APP_ACTOR`], and
/// registers `app` plus its prompt block once the registry is up. Disabled
/// → only wire contracts are declared.
pub struct AppPlugin;

#[async_trait::async_trait]
impl runtime::Plugin for AppPlugin {
    fn name(&self) -> &'static str {
        "app"
    }

    async fn declare_wire(&mut self, rt: &runtime::Runtime) -> anyhow::Result<()> {
        declare_wire(rt).await
    }

    async fn start(self: Box<Self>, rt: &Runtime) -> anyhow::Result<()> {
        declare_wire(rt).await?;
        let cfg: AppConfig = rt.section("app").unwrap_or_else(|e| {
            tracing::debug!("no [app] config section, using defaults: {e}");
            AppConfig::default()
        });
        if !cfg.enabled {
            tracing::info!("app disabled by config");
            return Ok(());
        }
        let helper = Arc::new(helper::Helper::new(
            helper_path(),
            hash(),
            rt.shutdown.clone(),
        ));
        let core = Arc::new(actor::Core::new(rt.clone(), helper));
        let actor =
            Apps::spawn_with_mailbox(Apps::new(core.clone()), runtime::subscriber_mailbox());
        actor.register(APP_ACTOR)?;
        rt.subscribe::<Apps, agent::AgentEvent>(&actor).await;

        let rt = rt.clone();
        tokio::spawn(async move {
            if let Some(reg) = rt
                .lookup_when::<tools::ToolRegistry>(tools::REGISTRY_ACTOR)
                .await
            {
                let _ = reg
                    .ask(tools::RegisterTool(Arc::new(AppTool {
                        core: core.clone(),
                    })))
                    .await;
                let _ = reg
                    .ask(tools::RegisterTool(Arc::new(TaskDraftTool {
                        core: core.clone(),
                    })))
                    .await;
                let _ = reg
                    .ask(tools::RegisterTool(Arc::new(AgentDraftTool {
                        core: core.clone(),
                    })))
                    .await;
                let _ = reg
                    .ask(tools::RegisterTool(Arc::new(RoutineDraftTool {
                        core: core.clone(),
                    })))
                    .await;
                let _ = reg
                    .ask(tools::RegisterTool(Arc::new(StudyDraftTool {
                        core: core.clone(),
                    })))
                    .await;
                launch_card::register(&reg, core.clone()).await; // 159:W6
                let _ = reg
                    .ask(tools::RegisterPrompt {
                        plugin: "app",
                        text: prompt(),
                    })
                    .await;
                for (lang, checker) in [
                    (
                        "mermaid",
                        Arc::new(fence::Mermaid(core.clone())) as Arc<dyn tools::FenceChecker>,
                    ),
                    ("openui", Arc::new(fence::OpenUi(core))),
                ] {
                    let _ = reg
                        .ask(tools::RegisterFenceChecker {
                            lang: lang.into(),
                            checker,
                        })
                        .await;
                }
                let _ = reg
                    .tell(tools::RegisterLifecycle {
                        owner: "app",
                        opened: None,
                        close: actor.reply_recipient(),
                    })
                    .await;
            }
        });
        Ok(())
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn hash_is_one_sha256_line_and_skill_embeds_it() {
        let h = hash();
        assert_eq!(h.len(), 64);
        assert!(h.bytes().all(|b| b.is_ascii_hexdigit()));
        let s = skill();
        assert!(s.contains(h));
        assert!(s.contains("Stack("), "catalog filled in");
        assert!(!s.contains("{{catalog}}") && !s.contains("{{hash}}"));
    }

    /// 58 step 14: the helper beside the binary is `theuth-app-parser-<hash>.exe` on Windows;
    /// `is_file` on the suffix-less name reported it missing there.
    #[test]
    fn default_helper_path_carries_exe_suffix() {
        if std::env::var_os("THEUTH_APP_PARSER").is_some_and(|p| !p.is_empty()) {
            return; // override in effect (app-parser-env.sh); the default path is not built
        }
        let name = helper_path()
            .file_name()
            .unwrap()
            .to_string_lossy()
            .into_owned();
        assert_eq!(
            name,
            format!(
                "theuth-app-parser-{}{}",
                hash(),
                std::env::consts::EXE_SUFFIX
            )
        );
    }

    #[test]
    fn wire_enums_are_snake_case() {
        assert_eq!(
            serde_json::to_string(&Trigger::StateChange).unwrap(),
            "\"state_change\""
        );
        assert_eq!(
            serde_json::to_string(&CallStatus::NeedsApproval).unwrap(),
            "\"needs_approval\""
        );
        assert!(CallStatus::Busy.is_error() && !CallStatus::NeedsApproval.is_error());
    }
}
