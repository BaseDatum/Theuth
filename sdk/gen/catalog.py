#!/usr/bin/env python3
"""Write sdk/catalog.md from bindings/openrpc.json (`x-theuth.events`). Stdlib only. Design 216 §7.

    python3 sdk/gen/catalog.py           # rewrite sdk/catalog.md
    python3 sdk/gen/catalog.py --check   # exit 1 when sdk/catalog.md is not what the bindings produce

One row per subscribable name: `<topic>#<type>` for each `oneOf` branch of a tagged-enum topic (the
branch's `type.const`), `<topic>` for a single-struct topic. Topics or entries whose `exposure` is
`private`/`internal` (when the bindings carry it) are left out.
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SRC = ROOT / "bindings" / "openrpc.json"
OUT = ROOT / "sdk" / "catalog.md"
DELTAS = {"TextDelta", "ReasoningDelta", "ToolCallProgress", "VisionProgress"}  # §7.3: need `deltas: true`


def first_sentence(text):
    text = " ".join((text or "").split())
    m = re.search(r"(?<=[.!?])\s", text)
    return (text[: m.start()] if m else text).replace("|", "\\|")


def resolve(schemas, s):
    seen = 0
    while isinstance(s, dict) and "$ref" in s and seen < 32:
        s, seen = schemas[s["$ref"].rsplit("/", 1)[-1]], seen + 1
    return s


def type_const(s):
    return ((s.get("properties") or {}).get("type") or {}).get("const")


def rows(doc):
    schemas = doc["components"]["schemas"]
    out = []
    for e in sorted(doc["x-theuth"]["events"], key=lambda e: e["topic"]):
        if e.get("exposure") in ("private", "internal"):
            continue
        topic, version = e["topic"], e.get("version", 1)
        s = resolve(schemas, e["schema"])
        if "oneOf" in s:
            for b in s["oneOf"]:
                b = resolve(schemas, b)
                t = type_const(b)
                if t and b.get("exposure") not in ("private", "internal"):
                    out.append((f"{topic}#{t}", version, t in DELTAS, first_sentence(b.get("description"))))
        else:
            out.append((topic, version, False, first_sentence(s.get("description"))))
    return out


def render(doc):
    r = rows(doc)
    topics = len({name.split("#")[0] for name, *_ in r})
    lines = [
        "# Event catalog",
        "",
        "<!-- generated by `python3 sdk/gen/catalog.py` from bindings/openrpc.json; do not edit -->",
        "",
        f"{len(r)} subscribable names in {topics} topics. Use a name in `plugin.yaml` `subscribe`",
        "(`topic` + `types`) and in `on(name)`. Event `data` is the wire JSON exactly as the feed carries it;",
        "ignore unknown fields and unknown `type`s (design 216 §7.5). Δ marks delta-class types, which need",
        "`deltas: true` on the subscription. Plugin events (`<plugin>.<event>`) come from manifests, not from",
        "this list. The JSON Schema of each topic is in `bindings/openrpc.json` under `x-theuth.events`.",
        "",
        "| Name | Version | Δ | Description |",
        "|---|---|---|---|",
    ]
    lines += [f"| `{n}` | {v} | {'Δ' if d else ''} | {desc} |" for n, v, d, desc in r]
    return "\n".join(lines) + "\n"


def main():
    text = render(json.loads(SRC.read_text(encoding="utf-8")))
    if "--check" in sys.argv[1:]:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
            print(f"{OUT.relative_to(ROOT)} is stale: run python3 sdk/gen/catalog.py", file=sys.stderr)
            return 1
        print(f"{OUT.relative_to(ROOT)} matches {SRC.relative_to(ROOT)}")
        return 0
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
